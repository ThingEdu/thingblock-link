use std::path::{Path, PathBuf};

struct BuildConfig {
    with_esp32: bool,
}

/// Build settings; edit here to change what the helper ships with.
const CONFIG: BuildConfig = BuildConfig { with_esp32: true };

fn main() {
    println!("cargo:rerun-if-changed=build.rs");
    compile_protos();
    build_arduino_cli_yaml(&CONFIG);
    emit_cfgs(&CONFIG);
}

/// Compile the vendored arduino-cli protos when present.
///
/// Uses `protox` (a pure-Rust proto compiler) so the build needs no system
/// `protoc`; it also bundles the `google/protobuf/*` well-known types. The
/// resulting descriptor set is handed to tonic's `compile_fds`. If `proto/`
/// holds no `.proto` files, codegen is skipped so the crate still builds.
fn compile_protos() {
    println!("cargo:rerun-if-changed=proto");

    let proto_root: &Path = Path::new("proto");
    if !proto_root.exists() {
        return;
    }

    let protos: Vec<PathBuf> = collect_protos(proto_root);
    if protos.is_empty() {
        return;
    }

    let fds = protox::compile(&protos, [proto_root]).expect("protox: compile arduino-cli protos");

    tonic_prost_build::configure()
        .build_server(false) // the helper is a gRPC client only
        .include_file("mod.rs") // one nested module tree for every proto package
        .compile_fds(fds)
        .expect("tonic: generate arduino-cli client");
}

fn collect_protos(dir: &Path) -> Vec<PathBuf> {
    let mut protos: Vec<PathBuf> = Vec::new();
    for entry in std::fs::read_dir(dir).expect("read proto dir") {
        let path: PathBuf = entry.expect("proto dir entry").path();
        if path.is_dir() {
            protos.extend(collect_protos(&path));
        } else if path.extension().is_some_and(|ext| ext == "proto") {
            protos.push(path);
        }
    }
    protos
}

/// Writes the arduino-cli daemon config `arduino-cli.yaml` to the crate root.
fn build_arduino_cli_yaml(config: &BuildConfig) {
    // The daemon reads its config from the crate root in dev (`default_config_dir`).
    let path = Path::new(&std::env::var("CARGO_MANIFEST_DIR").unwrap()).join("arduino-cli.yaml");

    // esp32 is not bundled (its toolchain is ~1GB installed); the editor installs it on
    // demand via the board manager, which needs this index.
    let additional_urls = if config.with_esp32 {
        "\n    - https://espressif.github.io/arduino-esp32/package_esp32_index.json"
    } else {
        " []"
    };

    let yaml = format!(
        "\
# Generated by build.rs from BuildConfig;
# Paths are relative on purpose: arduino-cli resolves them against its working
# directory, which the helper sets to this file's folder, so the same file works
# in-tree and packaged beside the binary.
board_manager:
  additional_urls:{additional_urls}
directories:
  data: data
  downloads: data/staging
  user: data/user
"
    );

    std::fs::write(&path, yaml).unwrap_or_else(|e| panic!("write {}: {e}", path.display()));
}

/// Exposes build settings to the crate as `cfg` flags.
fn emit_cfgs(config: &BuildConfig) {
    println!("cargo::rustc-check-cfg=cfg(with_esp32)");
    if config.with_esp32 {
        println!("cargo::rustc-cfg=with_esp32");
    }
}
